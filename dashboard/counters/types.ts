import type { DashboardEnv } from "../config";

// Один счётчик = один файл в этой папке.
//
// Договор нарочно узкий: счётчик получает настройки пульта и возвращает то,
// что показать. Он не знает ни про соседние счётчики, ни про вёрстку страницы,
// ни про приложение. Поэтому новый счётчик = новый файл + одна строка
// в registry.ts, и ни один существующий файл при этом не переписывается.

export type CounterValue = {
  /** Крупная цифра или короткая строка: «14», «3 из 7», «—». */
  value: string;
  /** Подпись помельче под цифрой: «за последние 7 дней». Необязательна. */
  caption?: string;
};

export type Counter = {
  id: string;
  /** Заголовок плитки: «Записей за неделю». */
  title: string;
  /**
   * Собрать данные. Вызывается на КАЖДЫЙ запрос страницы — никакого кэша,
   * нажал F5 и увидел свежее.
   *
   * Может спокойно бросать исключение: упавший счётчик покажет «нет данных»
   * и не уронит ни соседей, ни страницу.
   */
  collect(env: DashboardEnv): CounterValue | Promise<CounterValue>;
};
