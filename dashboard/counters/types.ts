import type { DashboardEnv } from "../config";
import type { Demo } from "../demo";
import type { Period } from "../period";

// Один счётчик = один файл в этой папке.
//
// Договор нарочно узкий: счётчик получает настройки и период, возвращает то,
// что показать. Он не знает ни про соседние счётчики, ни про вёрстку страницы,
// ни про приложение. Поэтому новый счётчик = новый файл + одна строка
// в registry.ts, и ни один существующий файл при этом не переписывается.

export type CounterContext = {
  env: DashboardEnv;
  /** Период один на весь пульт: переключатель стоит над счётчиками, а не в карточке. */
  period: Period;
  /**
   * Показывать ли учебные строки. Тоже один на весь пульт и по той же причине:
   * счётчик, считающий по своему набору строк, нельзя сравнить с соседним.
   */
  demo: Demo;
};

/** Один столбик графика. Дни без событий приходят сюда с нулём, а не пропускаются. */
export type CounterDay = { date: string; count: number };

export type CounterNote = {
  /** alarm — что-то сломалось и надо идти чинить; quiet — оговорка к цифрам. */
  tone: "alarm" | "quiet";
  text: string;
};

/**
 * Несколько чисел в ряд, когда смысл — в их СРАВНЕНИИ, а не в каждом отдельно.
 * Три источника одного и того же события читаются только рядом.
 */
export type CounterFigure = {
  label: string;
  value: string;
  /** Оговорка под числом: «из них через бота 8». Необязательна. */
  note?: string;
};

/**
 * Строка списка «пойти и разобраться»: конкретный случай с конкретным человеком.
 *
 * Счётчик, который говорит «трое потерялись» и не говорит КТО, заставляет
 * владельца гадать — а гадать по этой цифре нельзя.
 */
export type CounterCase = {
  /** Ключ для React и для глаза: по нему случай находится в источнике. */
  id: string;
  /** Кто и когда: «чат 254584880 · 30 августа, 17:03». */
  title: string;
  /** Что именно случилось, человеческим языком. */
  detail: string;
  /** О чём был разговор — из gist, если бот успел его записать. */
  gist?: string;
  /** Учебная строка: дорисована, тревожиться не надо. */
  demo?: boolean;
  /** alarm — человек пострадал; quiet — след потерян, но клиент придёт. */
  tone: "alarm" | "quiet";
};

export type CounterValue = {
  /** Крупная цифра или короткая строка: «14», «3 из 7», «—». */
  value: string;
  /** Подпись помельче под цифрой: «3 человека». Необязательна. */
  caption?: string;
  /**
   * График по дням. Необязателен: не всякому счётчику он нужен.
   *
   * realFrom — день, с которого в цифрах начинается НАСТОЯЩЕЕ. Всё левее
   * дорисовано учебной командой. График отбивает эту границу линией; без неё
   * учебный месяц и живые сутки выглядели бы одним рядом, и график врал бы
   * ровно тем способом, от которого его тут берегут.
   */
  chart?: { title: string; days: CounterDay[]; realFrom?: string };
  /** Сигналы к действию и честные оговорки. Показываются под цифрой. */
  notes?: CounterNote[];
  /** Числа в ряд — под крупной цифрой, до графика. */
  figures?: CounterFigure[];
  /** Случаи к разбору. Показываются последними: это уже работа, а не сводка. */
  cases?: CounterCase[];
};

export type Counter = {
  id: string;
  /** Заголовок плитки: «Обращения». */
  title: string;
  /**
   * Что это за счётчик — простыми словами: откуда данные, как считается,
   * что значит сигнал. Показывается по клику на ℹ️.
   *
   * Живёт рядом с кодом счётчика нарочно: меняешь формулу — правишь объяснение
   * в том же файле. Через месяц по этому тексту надо вспомнить, как всё устроено,
   * не открывая код.
   */
  info: string[];
  /**
   * Собрать данные. Вызывается на КАЖДЫЙ запрос страницы — никакого кэша,
   * нажал F5 и увидел свежее.
   *
   * Может спокойно бросать исключение: упавший счётчик покажет «нет данных»
   * и не уронит ни соседей, ни страницу.
   */
  collect(ctx: CounterContext): CounterValue | Promise<CounterValue>;
};
