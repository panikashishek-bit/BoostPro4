import type { DashboardEnv } from "../config";
import type { Period } from "../period";

// Один счётчик = один файл в этой папке.
//
// Договор нарочно узкий: счётчик получает настройки и период, возвращает то,
// что показать. Он не знает ни про соседние счётчики, ни про вёрстку страницы,
// ни про приложение. Поэтому новый счётчик = новый файл + одна строка
// в registry.ts, и ни один существующий файл при этом не переписывается.

export type CounterContext = {
  env: DashboardEnv;
  /** Период один на весь пульт: переключатель стоит над счётчиками, а не в карточке. */
  period: Period;
};

/** Один столбик графика. Дни без событий приходят сюда с нулём, а не пропускаются. */
export type CounterDay = { date: string; count: number };

export type CounterNote = {
  /** alarm — что-то сломалось и надо идти чинить; quiet — оговорка к цифрам. */
  tone: "alarm" | "quiet";
  text: string;
};

export type CounterValue = {
  /** Крупная цифра или короткая строка: «14», «3 из 7», «—». */
  value: string;
  /** Подпись помельче под цифрой: «3 человека». Необязательна. */
  caption?: string;
  /** График по дням. Необязателен: не всякому счётчику он нужен. */
  chart?: { title: string; days: CounterDay[] };
  /** Сигналы к действию и честные оговорки. Показываются под цифрой. */
  notes?: CounterNote[];
};

export type Counter = {
  id: string;
  /** Заголовок плитки: «Обращения». */
  title: string;
  /**
   * Что это за счётчик — простыми словами: откуда данные, как считается,
   * что значит сигнал. Показывается по клику на ℹ️.
   *
   * Живёт рядом с кодом счётчика нарочно: меняешь формулу — правишь объяснение
   * в том же файле. Через месяц по этому тексту надо вспомнить, как всё устроено,
   * не открывая код.
   */
  info: string[];
  /**
   * Собрать данные. Вызывается на КАЖДЫЙ запрос страницы — никакого кэша,
   * нажал F5 и увидел свежее.
   *
   * Может спокойно бросать исключение: упавший счётчик покажет «нет данных»
   * и не уронит ни соседей, ни страницу.
   */
  collect(ctx: CounterContext): CounterValue | Promise<CounterValue>;
};
