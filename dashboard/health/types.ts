import type { DashboardEnv } from "../config";

// Один источник данных = один файл в этой папке.
//
// Чтобы добавить источник: создай рядом файл, экспортируй из него объект
// HealthSource и допиши его в список в registry.ts. Ни соседние источники,
// ни страница, ни — тем более — код приложения при этом не меняются.

export type HealthState =
  /** Нашёлся и проверен. Зелёная строка. */
  | "ok"
  /** Не подключён: чего-то не хватает, и мы знаем, чего именно. Это НЕ ошибка. */
  | "missing"
  /** Подключён, но сломан: настроен, а прочитать не вышло. */
  | "broken";

export type HealthReport = {
  state: HealthState;
  /**
   * Что именно происходит — человеческим языком и с именем недостающей
   * переменной или файла. Ни «ошибка», ни стектрейсов: это читает владелец
   * пульта, а не разработчик, и по строке он должен понять, что чинить.
   */
  detail: string;
};

export type HealthSource = {
  /** Короткий ключ, только для React. */
  id: string;
  /** Как источник называется по-человечески: «лог событий», «расшифровки». */
  title: string;
  /** Проверка. Получает настройки пульта и НИЧЕГО не знает про остальные источники. */
  check(env: DashboardEnv): HealthReport | Promise<HealthReport>;
};
